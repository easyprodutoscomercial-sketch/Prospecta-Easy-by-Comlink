/**
 * Normalize a string by removing accents and converting to uppercase.
 */
function normalize(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .trim();
}

/**
 * Look up coordinates for a Brazilian city.
 *
 * @param cidade - City name (may contain accents, any casing)
 * @param estado - Two-letter state abbreviation (e.g. "SP", "RJ")
 * @returns [lat, lng] tuple or null if not found / inputs are empty
 */
export function getContactCoords(
  cidade: string | null,
  estado: string | null
): [number, number] | null {
  if (!cidade || !estado) return null;

  const normalizedCidade = normalize(cidade);
  const normalizedEstado = normalize(estado);

  if (!normalizedCidade || !normalizedEstado) return null;

  const key = `${normalizedCidade}-${normalizedEstado}`;
  return BRAZIL_CITIES_COORDS[key] ?? null;
}
